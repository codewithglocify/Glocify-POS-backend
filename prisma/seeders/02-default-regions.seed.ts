export default async function (prisma: PrismaClient) {
  const countryRegions = COUNTRIES.map((c) => c.regionCode);

  await prisma.region.createMany({
    data: REGIONS,
    skipDuplicates: true,
  });

  const regions = await prisma.region.findMany({
    where: {
      code: { in: countryRegions },
    },
  });

  const regionCodes = Object.fromEntries(regions.map((r) => [r.code, r.id]));
  const countries = COUNTRIES.map((country) => {
    const c = {
      ...country,
      regionId: regionCodes[country.regionCode],
    } as unknown as Omit<(typeof COUNTRIES)[number], 'regionCode'> & { regionCode: undefined; regionId: string }; // HACK: force regionCode to be undefined for delete.

    delete c.regionCode;

    return c;
  });

  await prisma.country.createMany({
    data: countries,
    skipDuplicates: true,
  });
}
